"""Build the exact folder that would be published, for the owner to review. Publishes nothing.

    python scripts/publish/make_public_tree.py --out build/public-tree-YYYYMMDD

Takes the tracked + untracked (not ignored) files, drops private and internal material, puts the public README and the
proposed licence in place, and writes MANIFEST.txt (path, bytes, sha256) plus EXCLUDED.txt (what was left out and why).
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXCLUDE = [  # (prefix or suffix rule, reason)
    ("eval/", "evaluation evidence: receipts, owner-review media and run folders (keep private; cite numbers in the report)"),
    ("owner-review/", "private owner review page and media"),
    ("research/", "publisher listings and acquisition plans (working material)"),
    ("infra/aws/manual/", "account-specific JSON and the private neutral-name -> publisher-file clip map"),
    ("infra/gcp/", "development jobs on the team's private GCP project (paths and lease notes)"),
    ("build/", "build outputs"),
    (".next-", "scratch folders"),
    ("docs/publish/README.public.md", "becomes README.md in the public tree"),
    ("docs/publish/LICENSE-Apache-2.0-proposed.txt", "becomes LICENSE in the public tree"),
    ("README.md", "internal README replaced by the public one"),
    ("docs/report/Floorsight-Technical-Report-v0.3-20261023.md", "superseded by report v0.4 (24 Oct)"),
    ("docs/report/Floorsight-Technical-Report-v0.4-20261024.md", "superseded by report v0.5 (24 Oct, motion smoothing)"),
    ("docs/report/Floorsight-Video-Script-v1-20261023.md", "superseded: the narration is generated by scripts/video/floorsight_spec.py"),
    ("docs/diagrams/floorsight-architecture-20261020", "superseded by the 24 Oct architecture diagram"),
    ("docs/diagrams/floorsight-architecture-20261023", "superseded by the 24 Oct architecture diagram"),
    ("docs/Floorsight-Project-Overview.before-", "pre-edit copy of the project overview"),
    ("docs/winning-plan-20261019.md", "internal planning note"),
    ("scripts/verify_owner_review", "internal tools that check the private owner review page"),
    ("docs/publish/PUBLISH-CHECKLIST.md", "internal: the owner's publishing decisions"),
    ("docs/publish/DEVPOST.md", "internal: submission text, pasted into Devpost by the owner"),
]
# private strings that must not appear in any published file; the build stops if one does (fail-closed). The list
# itself is private (it names the private strings), so it lives in an excluded folder, one regex per line.
PRIVATE_PATTERNS_FILE = ROOT / "infra/aws/manual/private-patterns.txt"
INTERNAL_NOTE_SUFFIXES = (".txt",)  # dated working notes in docs/ (e.g. docs/Danger-Zone-20261020.txt)


def files() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return sorted(f for f in set(out.splitlines()) if (ROOT / f).is_file() and "__pycache__" not in f)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--keep-working-notes", action="store_true", help="keep docs/*.txt dated working notes")
    a = ap.parse_args()
    if not PRIVATE_PATTERNS_FILE.is_file():
        raise SystemExit(f"no private-string list at {PRIVATE_PATTERNS_FILE}: refusing to build an unchecked tree")
    patterns = [ln.strip() for ln in PRIVATE_PATTERNS_FILE.read_text(encoding="utf-8").splitlines() if ln.strip()]
    if a.out.exists():
        raise SystemExit(f"{a.out} exists; make a new one")
    a.out.mkdir(parents=True)
    kept, excluded = [], []
    for f in files():
        reason = next((r for p, r in EXCLUDE if f == p or f.startswith(p)), None)
        if reason is None and not a.keep_working_notes and f.startswith("docs/") and f.count("/") == 1 and f.endswith(INTERNAL_NOTE_SUFFIXES):
            reason = "dated internal working note (owner decides whether to publish)"
        if reason is None and f.startswith("docs/report/") and ("DRAFT" in f or "-before-" in f):
            reason = "superseded draft or pre-edit copy of a report/script (the current version is published)"
        if f.endswith((".tfvars", ".tfstate", ".tfstate.backup", ".tfplan", ".tgz")) or "/plan-" in f or "/apply-" in f:
            reason = "Terraform state, plans or archives"
        if reason:
            excluded.append((f, reason))
            continue
        dst = a.out / f
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, dst)
        kept.append(f)
    shutil.copy2(ROOT / "docs/publish/README.public.md", a.out / "README.md")
    shutil.copy2(ROOT / "docs/publish/LICENSE-Apache-2.0-proposed.txt", a.out / "LICENSE")
    kept += ["README.md", "LICENSE"]
    with (a.out / "MANIFEST.txt").open("w", encoding="utf-8") as m:
        for f in sorted(kept):
            b = (a.out / f).read_bytes()
            m.write(f"{f}\t{len(b)}\t{hashlib.sha256(b).hexdigest()}\n")
    with (a.out / "EXCLUDED.txt").open("w", encoding="utf-8") as e:
        for f, r in excluded:
            e.write(f"{f}\t{r}\n")
    print(f"public tree: {len(kept)} files kept, {len(excluded)} excluded -> {a.out}")
    hits = []
    for f in kept:
        try:
            text = (a.out / f).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        hits += [(f, pat, m.group(0)) for pat in patterns for m in [re.search(pat, text, re.I)] if m]
    if hits:
        with (a.out / "PRIVATE-STRINGS-FOUND.txt").open("w", encoding="utf-8") as h:
            for f, pat, m in hits:
                h.write(f"{f}\t{pat}\t{m}\n")
        print(f"NOT PUBLISHABLE: {len(hits)} private-string hits in {len({f for f, _, _ in hits})} files -> PRIVATE-STRINGS-FOUND.txt")
        return 3
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
